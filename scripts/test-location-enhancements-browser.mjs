const origin = `https://${process.env.REPLIT_DEV_DOMAIN}`;
const targets = await (await fetch(`http://127.0.0.1:${process.env.CDP_PORT ?? 9223}/json/list`)).json();
const socket = new WebSocket(targets.find(t => t.type === "page").webSocketDebuggerUrl);
await new Promise(resolve => socket.addEventListener("open", resolve, { once: true }));
let seq = 0;
const pending = new Map(), errors = [], results = [];
socket.addEventListener("message", event => {
  const message = JSON.parse(event.data);
  if (message.id) {
    const p = pending.get(message.id);
    if (p) { pending.delete(message.id); message.error ? p.reject(message.error) : p.resolve(message.result); }
  } else if (message.method === "Runtime.exceptionThrown") errors.push(message.params.exceptionDetails);
});
const send = (method, params = {}) => new Promise((resolve, reject) => {
  const id = ++seq; pending.set(id, { resolve, reject }); socket.send(JSON.stringify({ id, method, params }));
});
const evaluate = async expression => {
  const result = await send("Runtime.evaluate", { expression, returnByValue: true, awaitPromise: true });
  if (result.exceptionDetails) throw new Error(JSON.stringify(result.exceptionDetails));
  return result.result.value;
};
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const wait = async (expression, label, timeout = 60000) => {
  const until = Date.now() + timeout;
  while (Date.now() < until) { if (await evaluate(expression)) { await delay(120); return; } await delay(150); }
  throw new Error(`Timed out: ${label}`);
};
const visible = `(()=>{const b=document.querySelector('[data-location-mobile-actions]');return !!b && getComputedStyle(b).display!=='none' && b.getClientRects().length>0})()`;
